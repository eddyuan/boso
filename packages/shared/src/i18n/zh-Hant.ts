/**
 * Traditional Chinese.
 *
 * Written out in full rather than spread over `zh-Hans` with a handful of
 * overrides. That would type-check — and would silently leave a Traditional reader
 * looking at Simplified characters for every key nobody remembered to override,
 * which reads as deliberate in a way an English fallback doesn't. A complete record
 * is also the only shape the missing-key check works against.
 *
 * It is not a character conversion. Traditional and Simplified differ in vocabulary
 * as well as glyphs, and this targets Taiwan usage (the largest Traditional market)
 * while staying legible in Hong Kong:
 *
 *   帖子 → 貼文        关注 → 追蹤        点赞 → 按讚
 *   设置 → 設定        登录 → 登入        默认 → 預設
 *   邮箱 → 電子郵件    短信 → 簡訊        日历 → 行事曆
 *   相册 → 相簿        头像 → 大頭貼      用户 → 使用者
 *   评论 → 留言        视频 → 影片        国家区号 → 國碼
 *
 * Quotation marks follow the Traditional convention (「」) rather than the
 * Simplified one (“”), and the phone-number example is a Taiwan number.
 *
 * `_one` and `_other` are identical throughout, as in `zh-Hans`: Chinese has one
 * plural category, so `Intl.PluralRules` never selects `_one`.
 */
